/* what the code leaves in its registers for later code to read, kept as the game's state (the parts of
   them no routine sets before it reads: decompiler/carried.py) */
/* the high byte of the word the code takes for an x on the screen in D1, and the high word above it:
   what the area exits' routines put there for a speed or a place (turtle_exit_go_to_place 02CE0C "lsl.l */
extern uint32_t screen_x_high;
/* the high word of D2, which direction_to reads with a distance across after swapping it with D1: what
   the area exits leave there (a turtle's place times 256, turtle_exit_go_to_place 02CE0E "lsl.l */
extern uint32_t distance_high_word;
/* the low byte of the distance up and down or across that the routines that look for a turtle close by
   work out in D5 (krang_find_close_turtle 00E89E "cmpi.w */
extern uint32_t distance_low_byte;
/* D6's low word: the banks and the rate of a fade (fade_palettes_start 00965C "move.w D6, $63418.l": the
   ending's and the opening's fades put them there), the bank a palette request reached
   (palette_request_area), the board's control byte send_sound_command writes (00923A "move.b D6,
   $a0001.l"); the players' boxes read its high byte as the high byte of the player's number */
extern uint32_t fade_banks;
/* the high word of what the code adds as an offset or tests as a long of flags in D7, whose low word
   only it sets: 0 after a count, a sound or a mask of its own (a moveq), FFFF where an enemy has not
   landed (enemy_landed 04863A "moveq */
extern uint32_t offset_high_word;
/* where A5 points in the palettes: the place in the palette RAM a palette request copies colours to
   (palette_request_list 0094AC "movea.l (A5,D6.w), A5", copy_palette_list moves it on), the palettes a
   fade goes to (fade_palettes_start 009662 "move.l A5, $63414.l": the ending's and the opening's fades
   put them there) */
extern uint32_t palette_place;

